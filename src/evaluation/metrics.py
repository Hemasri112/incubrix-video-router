from typing import Dict, List


def calculate_route_accuracy(
    selected_models: List[str],
    expected_models: List[str],
) -> float:
    """
    Calculate routing accuracy.

    Accuracy = correctly selected routes / total routes.
    """

    if len(selected_models) != len(expected_models):
        raise ValueError(
            "Selected models and expected models must have the same length."
        )

    if not selected_models:
        raise ValueError(
            "At least one routing result is required."
        )

    correct = sum(
        selected == expected
        for selected, expected in zip(
            selected_models,
            expected_models,
        )
    )

    return correct / len(selected_models)


def calculate_render_success_rate(
    successful_renders: int,
    total_renders: int,
) -> float:
    """
    Calculate the percentage of successful video renders.
    """

    if total_renders <= 0:
        raise ValueError(
            "Total renders must be greater than zero."
        )

    if successful_renders < 0:
        raise ValueError(
            "Successful renders cannot be negative."
        )

    if successful_renders > total_renders:
        raise ValueError(
            "Successful renders cannot exceed total renders."
        )

    return successful_renders / total_renders


def calculate_average_latency(
    runtimes: List[float],
) -> float:
    """
    Calculate average measured runtime in seconds.
    """

    if not runtimes:
        raise ValueError(
            "At least one runtime measurement is required."
        )

    if any(runtime < 0 for runtime in runtimes):
        raise ValueError(
            "Runtime values cannot be negative."
        )

    return sum(runtimes) / len(runtimes)


def calculate_local_resource_usage(
    peak_ram_gb: float,
    accelerator_time_seconds: float,
) -> Dict[str, float]:
    """
    Record local resource measurements.

    These values are measurements supplied by the benchmark,
    not estimates generated by this module.
    """

    if peak_ram_gb < 0:
        raise ValueError(
            "Peak RAM cannot be negative."
        )

    if accelerator_time_seconds < 0:
        raise ValueError(
            "Accelerator time cannot be negative."
        )

    return {
        "peak_ram_gb": peak_ram_gb,
        "accelerator_time_seconds": accelerator_time_seconds,
    }


def build_benchmark_summary(
    total_briefs: int,
    successful_renders: int,
    selected_models: List[str],
    expected_models: List[str],
    runtimes: List[float],
) -> Dict:
    """
    Build a summary of routing and generation benchmark results.
    """

    if total_briefs <= 0:
        raise ValueError(
            "Total briefs must be greater than zero."
        )

    if len(selected_models) != total_briefs:
        raise ValueError(
            "Selected model count must match total briefs."
        )

    if len(expected_models) != total_briefs:
        raise ValueError(
            "Expected model count must match total briefs."
        )

    if successful_renders > total_briefs:
        raise ValueError(
            "Successful renders cannot exceed total briefs."
        )

    return {
        "total_briefs": total_briefs,
        "successful_renders": successful_renders,
        "render_success_rate": calculate_render_success_rate(
            successful_renders,
            total_briefs,
        ),
        "route_accuracy": calculate_route_accuracy(
            selected_models,
            expected_models,
        ),
        "average_latency_seconds": calculate_average_latency(
            runtimes
        ),
    }